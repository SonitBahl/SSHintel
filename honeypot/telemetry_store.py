    # ---- Internal helpers ----

    def _query_scalar(self, sql, params=()):
        if self._conn is None:
            return 0
        try:
            with self._lock:
                cur = self._conn.execute(sql, params)
                row = cur.fetchone()
                return row[0] if row else 0
        except Exception as exc:
            print(f"!!! SQLite query error: {exc}")
            return 0

    def _query_all(self, sql, params=()):
        if self._conn is None:
            return []
        try:
            with self._lock:
                cur = self._conn.execute(sql, params)
                return cur.fetchall()
        except Exception as exc:
            print(f"!!! SQLite query error: {exc}")
            return []

    @staticmethod
    def _row_to_dict(row, include_id=False):
        keys = ["timestamp", "event_type", "session_id", "source_ip",
                "source_port", "username", "command", "cwd", "metadata",
                "event_id", "schema_version", "legacy_event_type", "sensor_id"]
        if include_id:
            keys = ["id"] + keys
        d = dict(zip(keys, row))
        if d.get("metadata"):
            try:
                d["metadata"] = json.loads(d["metadata"])
            except Exception:
                pass
        else:
            d.pop("metadata", None)
        return d
