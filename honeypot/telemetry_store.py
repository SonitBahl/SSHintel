"""SQLite telemetry store for SSHintel.

Provides a queryable, persistent store for the structured security events
generated by the honeypot. JSONL remains the raw source of truth; this module
is an additional persistence and analysis layer.

Thread safety: a single shared connection is protected by a threading.Lock,
so concurrent SSH sessions can safely record telemetry. WAL mode is enabled
for better concurrent read performance.
"""

from __future__ import annotations

import json
import sqlite3
import threading
from pathlib import Path
from typing import Any

# Flat (v1/v2) event-type names → dotted (v3) namespace names.
# The dotted form is stored in ``event_type``; the original flat name is
# preserved in ``legacy_event_type`` for backward compatibility.
EVENT_TYPES = {
    'connect': 'session.started',
    'auth_attempt': 'auth.attempted',
    'auth_success': 'auth.succeeded',
    'auth_failure': 'auth.failed',
    'command': 'command.executed',
    'disconnect': 'session.disconnected',
    'tarpit': 'session.tarpit',
    'connection_rejected': 'session.rejected',
}


def normalize_event_type(event_type):
    """Return the dotted namespace name for a flat event type.

    Unknown event types are returned unchanged so custom event types pass
    through without modification.
    """
    return EVENT_TYPES.get(event_type, event_type)


SCHEMA_VERSION = 4

DEFAULT_DB_PATH = Path(__file__).parent.parent / "data" / "sshintel.db"

CREATE_TABLES_SQL = """
CREATE TABLE IF NOT EXISTS events (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    timestamp       TEXT NOT NULL,
    event_type      TEXT NOT NULL,
    session_id      TEXT,
    source_ip       TEXT,
    source_port     INTEGER,
    username        TEXT,
    command         TEXT,
    cwd             TEXT,
    metadata        TEXT,
    event_id        TEXT,
    schema_version  TEXT,
    legacy_event_type TEXT,
    sensor_id       TEXT
);

CREATE TABLE IF NOT EXISTS sessions (
    session_id      TEXT PRIMARY KEY,
    source_ip       TEXT,
    username        TEXT,
    started_at      TEXT,
    ended_at        TEXT,
    duration        REAL,
    status          TEXT,
    disconnect_reason TEXT
);

CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS urls (
    url        TEXT PRIMARY KEY,
    first_seen TEXT NOT NULL,
    last_seen  TEXT NOT NULL,
    times_seen INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS artifacts (
    sha256       TEXT PRIMARY KEY,
    size         INTEGER NOT NULL,
    content_type TEXT NOT NULL DEFAULT '',
    first_seen   TEXT NOT NULL,
    last_seen    TEXT NOT NULL,
    times_seen   INTEGER NOT NULL DEFAULT 1,
    stored_path  TEXT NOT NULL,
    kind         TEXT NOT NULL DEFAULT 'downloaded'
);
"""

INDEXES_SQL = [
    "CREATE INDEX IF NOT EXISTS idx_events_timestamp ON events(timestamp);",
    "CREATE INDEX IF NOT EXISTS idx_events_event_type ON events(event_type);",
    "CREATE INDEX IF NOT EXISTS idx_events_session_id ON events(session_id);",
    "CREATE INDEX IF NOT EXISTS idx_events_source_ip ON events(source_ip);",
    "CREATE INDEX IF NOT EXISTS idx_events_username ON events(username);",
    "CREATE INDEX IF NOT EXISTS idx_events_legacy_event_type ON events(legacy_event_type);",
    "CREATE INDEX IF NOT EXISTS idx_events_sensor_id ON events(sensor_id);",
    "CREATE INDEX IF NOT EXISTS idx_events_source_port ON events(source_port);",
    "CREATE INDEX IF NOT EXISTS idx_sessions_source_ip ON sessions(source_ip);",
    "CREATE INDEX IF NOT EXISTS idx_sessions_started_at ON sessions(started_at);",
    "CREATE INDEX IF NOT EXISTS idx_urls_last_seen ON urls(last_seen);",
    "CREATE INDEX IF NOT EXISTS idx_urls_times_seen ON urls(times_seen);",
    "CREATE INDEX IF NOT EXISTS idx_artifacts_sha256 ON artifacts(sha256);",
    "CREATE INDEX IF NOT EXISTS idx_artifacts_times_seen ON artifacts(times_seen);",
    "CREATE INDEX IF NOT EXISTS idx_artifacts_kind ON artifacts(kind);",
]


class TelemetryStore:
    """Persistent SQLite store for SSH security events."""

    def __init__(self, db_path=None):
        if db_path is None:
            db_path = DEFAULT_DB_PATH
        self.db_path = Path(db_path)
        self._lock = threading.Lock()
        self._conn = None

    def open(self):
        if self._conn is not None:
            return
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = sqlite3.connect(
            str(self.db_path), check_same_thread=False, timeout=10
        )
        self._conn.execute("PRAGMA journal_mode=WAL;")
        self._create_schema()

    def close(self):
        if self._conn is not None:
            try:
                self._conn.close()
            except Exception:
                pass
            self._conn = None

    @property
    def is_open(self):
        return self._conn is not None

    def _create_schema(self):
        assert self._conn is not None
        with self._lock:
            self._conn.executescript(CREATE_TABLES_SQL)
            # Idempotent migration: add v2/v3/v4 columns to any pre-existing
            # database without dropping data. Must run before indexes so the
            # new columns exist when indexes are created.
            self._migrate_to_v4()
            for stmt in INDEXES_SQL:
                self._conn.execute(stmt)
            self._conn.execute(
                "INSERT OR REPLACE INTO meta(key, value) VALUES('schema_version', ?)",
                (str(SCHEMA_VERSION),),
            )
            self._conn.commit()

    def _migrate_to_v4(self):
        """Add ``event_id``, ``schema_version``, ``legacy_event_type``, and
        ``sensor_id`` columns to any pre-existing database without dropping data.

        ``ALTER TABLE ... ADD COLUMN`` is guarded with ``PRAGMA table_info``
        so the helper is explicitly idempotent and never fails on a partially
        migrated database (v1, v2, v3, or already-migrated v4).
        """
        assert self._conn is not None
        existing = {
            row[1]
            for row in self._conn.execute("PRAGMA table_info(events)")
        }
        if "event_id" not in existing:
            self._conn.execute("ALTER TABLE events ADD COLUMN event_id TEXT")
        if "schema_version" not in existing:
            self._conn.execute(
                "ALTER TABLE events ADD COLUMN schema_version TEXT"
            )
        if "legacy_event_type" not in existing:
            self._conn.execute(
                "ALTER TABLE events ADD COLUMN legacy_event_type TEXT"
            )
        if "sensor_id" not in existing:
            self._conn.execute("ALTER TABLE events ADD COLUMN sensor_id TEXT")

    def log_event(self, event):
        if self._conn is None:
            return
        # Normalize flat event-type names to dotted form and preserve the
        # original flat name as legacy_event_type for backward compatibility.
        event_type = event.get("event_type")
        dotted = normalize_event_type(event_type)
        event["event_type"] = dotted
        if dotted != event_type and not event.get("legacy_event_type"):
            event["legacy_event_type"] = event_type

        known_keys = {
            "timestamp", "event_type", "session_id", "source_ip",
            "source_port", "username", "command", "cwd",
            "event_id", "schema_version", "legacy_event_type",
            "sensor_id",
        }
        try:
            metadata = {k: v for k, v in event.items() if k not in known_keys}
            with self._lock:
                self._conn.execute(
                    "INSERT INTO events (timestamp, event_type, session_id, "
                    "source_ip, source_port, username, command, cwd, metadata, "
                    "event_id, schema_version, legacy_event_type, sensor_id) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                    (
                        event.get("timestamp"),
                        event.get("event_type"),
                        event.get("session_id"),
                        event.get("source_ip"),
                        event.get("source_port"),
                        event.get("username"),
                        event.get("command"),
                        event.get("cwd"),
                        json.dumps(metadata, ensure_ascii=False) if metadata else None,
                        event.get("event_id"),
                        event.get("schema_version"),
                        event.get("legacy_event_type"),
                        event.get("sensor_id"),
                    ),
                )
                self._conn.commit()
        except Exception as exc:
            print(f"!!! SQLite telemetry error: {exc}")

    def log_url(self, url: str, timestamp: str) -> None:
        """Insert or dedup-sert a URL sighting into the ``urls`` table.

        On first sighting: inserts with ``times_seen = 1``.
        On repeat sighting: updates ``last_seen`` and increments ``times_seen``,
        preserving the original ``first_seen``.
        """
        if self._conn is None:
            return
        try:
            with self._lock:
                self._conn.execute(
                    "INSERT INTO urls (url, first_seen, last_seen, times_seen) "
                    "VALUES (?, ?, ?, 1) "
                    "ON CONFLICT(url) DO UPDATE SET "
                    "last_seen = excluded.last_seen, "
                    "times_seen = times_seen + 1",
                    (url, timestamp, timestamp),
                )
                self._conn.commit()
        except Exception as exc:
            print(f"!!! SQLite URL telemetry error: {exc}")

    def log_artifact(self, sha256: str, size: int, content_type: str,
                     stored_path: str, kind: str, timestamp: str) -> bool:
        """Insert or dedup-sert an artifact into the ``artifacts`` table.

        On first sighting: inserts with ``times_seen = 1`` and returns ``True``.
        On repeat sighting: updates ``last_seen`` and increments ``times_seen``,
        preserving the original ``first_seen`` and ``stored_path``, returns
        ``False``.
        """
        if self._conn is None:
            return False
        try:
            with self._lock:
                existing = self._conn.execute(
                    "SELECT 1 FROM artifacts WHERE sha256 = ?", (sha256,)
                ).fetchone()
                is_new = existing is None
                self._conn.execute(
                    "INSERT INTO artifacts "
                    "(sha256, size, content_type, first_seen, last_seen, "
                    "times_seen, stored_path, kind) "
                    "VALUES (?, ?, ?, ?, ?, 1, ?, ?) "
                    "ON CONFLICT(sha256) DO UPDATE SET "
                    "last_seen = excluded.last_seen, "
                    "times_seen = times_seen + 1",
                    (sha256, size, content_type, timestamp, timestamp,
                     stored_path, kind),
                )
                self._conn.commit()
                return is_new
        except Exception as exc:
            print(f"!!! SQLite artifact telemetry error: {exc}")
            return False

    def record_session_connect(self, session_id, source_ip, connected_at):
        if self._conn is None:
            return
        try:
            with self._lock:
                self._conn.execute(
                    "INSERT OR IGNORE INTO sessions "
                    "(session_id, source_ip, started_at) VALUES (?, ?, ?)",
                    (session_id, source_ip, connected_at),
                )
                self._conn.commit()
        except Exception as exc:
            print(f"!!! SQLite session-connect error: {exc}")

    def record_session_finalize(self, session_id, username, ended_at,
                                duration, status, disconnect_reason):
        """Record or update a session's final state.

        ``source_ip`` is looked up from events if not already known.
        """
        if self._conn is None:
            return
        try:
            with self._lock:
                self._conn.execute(
                    "INSERT OR REPLACE INTO sessions "
                    "(session_id, source_ip, username, started_at, ended_at, "
                    "duration, status, disconnect_reason) "
                    "VALUES(?, "
                    "COALESCE((SELECT source_ip FROM sessions WHERE session_id=? AND source_ip IS NOT NULL AND source_ip != ''), "
                    "(SELECT source_ip FROM events WHERE session_id=? AND source_ip IS NOT NULL AND source_ip != '' LIMIT 1), ''), "
                    "?, "
                    "COALESCE((SELECT started_at FROM sessions WHERE session_id=?), ''), "
                    "?, ?, ?, ?)",
                    (session_id, session_id, session_id, username, session_id,
                     ended_at, duration, status, disconnect_reason),
                )
                self._conn.commit()
        except Exception as exc:
            print(f"!!! SQLite error recording session finalize: {exc}")
            print(f"!!! SQLite session-finalize error: {exc}")

    # ---- Query helpers ----

    def count_sessions(self):
        return self._query_scalar("SELECT COUNT(*) FROM sessions")

    def count_events(self):
        return self._query_scalar("SELECT COUNT(*) FROM events")

    def unique_ips(self):
        return self._query_scalar(
            "SELECT COUNT(DISTINCT source_ip) FROM events"
        )

    def total_auth_attempts(self):
        return self._query_scalar(
            "SELECT COUNT(*) FROM events WHERE legacy_event_type='auth_attempt'"
        )

    def successful_auths(self):
        return self._query_scalar(
            "SELECT COUNT(*) FROM events WHERE legacy_event_type='auth_success'"
        )

    def failed_auth_attempts(self):
        return self._query_scalar(
            "SELECT COUNT(*) FROM events WHERE legacy_event_type='auth_failure'"
        )

    def total_commands(self):
        return self._query_scalar(
            "SELECT COUNT(*) FROM events WHERE legacy_event_type='command'"
        )

    def top_commands(self, limit=10):
        rows = self._query_all(
            "SELECT command, COUNT(*) AS cnt "
            "FROM events WHERE legacy_event_type='command' AND command IS NOT NULL "
            "GROUP BY command ORDER BY cnt DESC LIMIT ?",
            (limit,),
        )
        return [{"command": r[0], "count": r[1]} for r in rows]

    def top_source_ips(self, limit=10):
        rows = self._query_all(
            "SELECT source_ip, COUNT(*) AS cnt "
            "FROM events WHERE source_ip IS NOT NULL "
            "GROUP BY source_ip ORDER BY cnt DESC LIMIT ?",
            (limit,),
        )
        return [{"source_ip": r[0], "count": r[1]} for r in rows]

    def top_usernames(self, limit=10):
        rows = self._query_all(
            "SELECT username, COUNT(*) AS cnt "
            "FROM events WHERE username IS NOT NULL "
            "GROUP BY username ORDER BY cnt DESC LIMIT ?",
            (limit,),
        )
        return [{"username": r[0], "count": r[1]} for r in rows]

    def events_in_range(self, start, end, limit=100):
        rows = self._query_all(
            "SELECT timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version, legacy_event_type, sensor_id "
            "FROM events WHERE timestamp >= ? AND timestamp <= ? "
            "ORDER BY id ASC LIMIT ?",
            (start, end, limit),
        )
        return [self._row_to_dict(r) for r in rows]

    def sessions_in_range(self, start, end, limit=100):
        rows = self._query_all(
            "SELECT session_id, source_ip, username, started_at, ended_at, "
            "duration, status, disconnect_reason "
            "FROM sessions WHERE started_at >= ? AND started_at <= ? "
            "ORDER BY started_at ASC LIMIT ?",
            (start, end, limit),
        )
        cols = ["session_id", "source_ip", "username", "started_at",
                "ended_at", "duration", "status", "disconnect_reason"]
        return [dict(zip(cols, r)) for r in rows]

    def get_session(self, session_id):
        """Return summary metadata for a single session, or None if unknown."""
        rows = self._query_all(
            "SELECT session_id, source_ip, username, started_at, ended_at, "
            "duration, status, disconnect_reason "
            "FROM sessions WHERE session_id = ?",
            (session_id,),
        )
        if not rows:
            return None
        cols = ["session_id", "source_ip", "username", "started_at",
                "ended_at", "duration", "status", "disconnect_reason"]
        return dict(zip(cols, rows[0]))

    def get_session_events(self, session_id, limit=500):
        """Return all events for a session, ordered chronologically."""
        rows = self._query_all(
            "SELECT timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version, legacy_event_type, sensor_id "
            "FROM events WHERE session_id = ? "
            "ORDER BY timestamp ASC, id ASC LIMIT ?",
            (session_id, limit),
        )
        return [self._row_to_dict(r) for r in rows]

    def get_events_after(self, event_id, limit=100):
        """Return events with id greater than ``event_id``, ordered by id.

        Used by the dashboard for incremental live updates. Returns at most
        ``limit`` events to avoid overwhelming the client.
        """
        rows = self._query_all(
            "SELECT id, timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version "
            "FROM events WHERE id > ? ORDER BY id ASC LIMIT ?",
            (event_id, limit),
        )
        return [self._row_to_dict(r, include_id=True) for r in rows]

    def get_latest_event_id(self):
        """Return the highest event id, or 0 if no events exist."""
        return self._query_scalar("SELECT COALESCE(MAX(id), 0) FROM events")

    def get_recent_events(self, limit=100):
        rows = self._query_all(
            "SELECT timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version, legacy_event_type, sensor_id "
            "FROM events ORDER BY id DESC LIMIT ?",
            (limit,),
        )
        return [self._row_to_dict(r) for r in rows]

    def get_recent_sessions(self, limit=50):
        rows = self._query_all(
            "SELECT session_id, source_ip, username, started_at, ended_at, "
            "duration, status, disconnect_reason "
            "FROM sessions ORDER BY started_at DESC LIMIT ?",
            (limit,),
        )
        cols = ["session_id", "source_ip", "username", "started_at",
                "ended_at", "duration", "status", "disconnect_reason"]
        return [dict(zip(cols, r)) for r in rows]

    def get_events_by_ip(self, source_ip, limit=100):
        rows = self._query_all(
            "SELECT timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version, legacy_event_type, sensor_id "
            "FROM events WHERE source_ip = ? "
            "ORDER BY id DESC LIMIT ?",
            (source_ip, limit),
        )
        return [self._row_to_dict(r) for r in rows]

    def get_events_by_sensor(self, sensor_id, limit=100):
        """Return events for a given sensor_id, most recent first."""
        rows = self._query_all(
            "SELECT timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version, legacy_event_type, sensor_id "
            "FROM events WHERE sensor_id = ? "
            "ORDER BY id DESC LIMIT ?",
            (sensor_id, limit),
        )
        return [self._row_to_dict(r) for r in rows]

    def get_events_by_port(self, source_port, limit=100):
        """Return events for a given source_port, most recent first."""
        rows = self._query_all(
            "SELECT timestamp, event_type, session_id, source_ip, "
            "source_port, username, command, cwd, metadata, "
            "event_id, schema_version, legacy_event_type, sensor_id "
            "FROM events WHERE source_port = ? "
            "ORDER BY id DESC LIMIT ?",
            (source_port, limit),
        )
        return [self._row_to_dict(r) for r in rows]

    def activity_by_hour(self, hours=24):
        rows = self._query_all(
            "SELECT strftime('%H', timestamp) AS hour, COUNT(*) AS cnt "
            "FROM events "
            "WHERE timestamp >= datetime('now', ?) "
            "GROUP BY hour ORDER BY hour ASC",
            (f"-{hours} hours",),
        )
        return [{"hour": r[0], "count": r[1]} for r in rows]

    # ---- Internal helpers ----

    def _query_scalar(self, sql, params=()):
        if self._conn is None:
            return 0
        try:
            with self._lock:
                cur = self._conn.execute(sql, params)
                row = cur.fetchone()
                return row[0] if row else 0
        except Exception as exc:
            print(f"!!! SQLite query error: {exc}")
            return 0

    def _query_all(self, sql, params=()):
        if self._conn is None:
            return []
        try:
            with self._lock:
                cur = self._conn.execute(sql, params)
                return cur.fetchall()
        except Exception as exc:
            print(f"!!! SQLite query error: {exc}")
            return []

    @staticmethod
    def _row_to_dict(row, include_id=False):
        keys = ["timestamp", "event_type", "session_id", "source_ip",
                "source_port", "username", "command", "cwd", "metadata",
                "event_id", "schema_version", "legacy_event_type", "sensor_id"]
        if include_id:
            keys = ["id"] + keys
        d = dict(zip(keys, row))
        if d.get("metadata"):
            try:
                d["metadata"] = json.loads(d["metadata"])
            except Exception:
                pass
        else:
            d.pop("metadata", None)
        return d
